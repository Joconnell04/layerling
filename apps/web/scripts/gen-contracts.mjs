// Generate lib/contracts.gen.ts and lib/contracts.schemas.gen.ts from contracts/schema/*.json.
// Run: npm run gen:contracts
//
// Every schema file is merged into one root schema so shared $defs (FileRef, Lab, ...) are emitted
// once. A $def that two files define differently gets a file prefix, and that file's refs are
// rewritten. mcp_tools.schema.json is skipped: the web app never calls the paint MCP server.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const schemaDir = join(webRoot, "..", "..", "contracts", "schema");
const outTypes = join(webRoot, "lib", "contracts.gen.ts");
const outSchemas = join(webRoot, "lib", "contracts.schemas.gen.ts");

const SKIP = new Set(["mcp_tools.schema.json"]);

const files = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".schema.json") && !SKIP.has(f))
  .sort();

const stable = (v) => JSON.stringify(v, Object.keys(flatKeys(v)).sort());
function flatKeys(v, acc = {}) {
  if (v && typeof v === "object") {
    for (const [k, x] of Object.entries(v)) {
      acc[k] = true;
      flatKeys(x, acc);
    }
  }
  return acc;
}

function rewriteRefs(node, renames) {
  if (Array.isArray(node)) return node.map((x) => rewriteRefs(x, renames));
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "$ref" && typeof v === "string" && v.startsWith("#/$defs/")) {
      const name = v.slice("#/$defs/".length);
      out[k] = `#/$defs/${renames[name] ?? name}`;
    } else {
      out[k] = rewriteRefs(v, renames);
    }
  }
  return out;
}

const defs = {};
const topLevel = {}; // file stem -> def name
const rawSchemas = {}; // file stem -> original schema (for ajv)

for (const file of files) {
  const stem = file.replace(".schema.json", "");
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  rawSchemas[stem] = schema;
  const fileDefs = schema.$defs ?? {};
  const renames = {};
  for (const [name, def] of Object.entries(fileDefs)) {
    if (defs[name] && stable(defs[name]) !== stable(rewriteRefs(def, {}))) {
      renames[name] = `${pascal(stem)}${name}`;
    }
  }
  for (const [name, def] of Object.entries(fileDefs)) {
    const target = renames[name] ?? name;
    const body = rewriteRefs(def, renames);
    if (!defs[target]) defs[target] = body;
  }
  const { $defs: _drop, ...rest } = schema;
  const title = rest.title ?? pascal(stem);
  const body = rewriteRefs(rest, renames);
  if (defs[title] && stable(defs[title]) !== stable(body)) {
    const alt = pascal(stem);
    defs[alt] = { ...body, title: alt };
    topLevel[stem] = alt;
  } else {
    defs[title] = body;
    topLevel[stem] = title;
  }
}

function pascal(s) {
  return s
    .split(/[_\-\s]+/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

// Pydantic emits a `title` on every property (json-schema-to-typescript turns each into a named
// alias like Id1, Id2) and 2020-12 `prefixItems` for tuples (unsupported). Normalize both.
function normalize(node, isDefRoot) {
  if (Array.isArray(node)) return node.map((x) => normalize(x, false));
  if (!node || typeof node !== "object") return node;
  // A $ref with sibling keys (description, default) makes the generator emit a copy (FileRef1).
  if (typeof node.$ref === "string" && !isDefRoot) return { $ref: node.$ref };
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "title" && !isDefRoot) continue;
    if (k === "prefixItems") {
      out.items = normalize(v, false);
      out.minItems = v.length;
      out.maxItems = v.length;
      continue;
    }
    if (k === "properties" || k === "$defs") {
      out[k] = Object.fromEntries(Object.entries(v).map(([p, s]) => [p, normalize(s, k === "$defs")]));
      continue;
    }
    out[k] = normalize(v, false);
  }
  return out;
}
for (const name of Object.keys(defs)) defs[name] = normalize(defs[name], true);

const root = {
  title: "P2PContracts",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(
    Object.entries(topLevel).map(([stem, name]) => [stem, { $ref: `#/$defs/${name}` }]),
  ),
  $defs: defs,
};

const banner = `/* eslint-disable */
// GENERATED by scripts/gen-contracts.mjs from contracts/schema/*.json. Do not edit.
// Regenerate: npm run gen:contracts`;

const ts = await compile(root, "P2PContracts", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  format: true,
  strictIndexSignatures: false,
  maxItems: -1,
  style: { singleQuote: false, printWidth: 100 },
});

const msgKinds = Object.entries(topLevel)
  .filter(([stem]) => stem.startsWith("msg_"))
  .map(([stem, name]) => `  ${stem.slice(4)}: ${name};`)
  .join("\n");

const footer = `
/** messages.kind -> payload type, for kinds that carry a payload model (contracts payloads.MESSAGE_PAYLOADS). */
export interface MessagePayloadMap {
${msgKinds}
}
`;

writeFileSync(outTypes, ts + footer);

const schemasTs = `// GENERATED by scripts/gen-contracts.mjs from contracts/schema/*.json. Do not edit.
// Regenerate: npm run gen:contracts
/* eslint-disable */

export const SCHEMAS = ${JSON.stringify(
  Object.fromEntries(Object.entries(rawSchemas).filter(([stem]) => stem.startsWith("msg_"))),
  null,
  2,
)} as const;
`;
writeFileSync(outSchemas, schemasTs);

console.log(
  `wrote ${Object.keys(defs).length} types from ${files.length} schemas to lib/contracts.gen.ts`,
);
