// Write app/tokens.css from design/tokens.json (the design system's tokens, repo root).
// Runs before dev, build and test. lib/tokens.test.ts fails when the checked-in file is stale.
//
// Output:
//   @theme  --color-<name>, --radius-<name>, --shadow-<name>, --font-<family>, --text-<style>
//           (with --line-height, --letter-spacing, --font-weight), plus --text-<style>-phone for
//           styles whose usage says "<N>px under <W>px". Tailwind's 4 px --spacing stays.
//   :root   --dur-*, --ease-*, --space-*, --border-* as plain custom properties.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TOKENS_JSON = join(web, "..", "..", "design", "tokens.json");
export const TOKENS_CSS = join(web, "app", "tokens.css");

// Geist Mono is loaded by next/font (geist/font/mono), which exposes its hashed family name as
// --font-geist-mono. Put it ahead of the token's own stack.
const FAMILY_PREFIX = { mono: "var(--font-geist-mono)" };

const px = (v) => (typeof v === "number" ? `${v}px` : String(v));

export function renderTokens(tokens) {
  const theme = [];
  const root = [];
  const line = (arr, name, value, note) => arr.push(`  --${name}: ${value};${note ? ` /* ${note} */` : ""}`);

  theme.push("  /* Color */");
  for (const t of tokens.color.tokens) line(theme, `color-${t.name}`, t.value);

  theme.push("", "  /* Radius */");
  for (const t of tokens.radius.tokens) line(theme, t.name, t.value);

  theme.push("", "  /* Shadow */");
  for (const t of tokens.shadow.tokens) line(theme, `shadow-${t.name}`, t.value);

  theme.push("", "  /* Families */");
  for (const [name, stack] of Object.entries(tokens.type.families)) {
    line(theme, `font-${name}`, FAMILY_PREFIX[name] ? `${FAMILY_PREFIX[name]}, ${stack}` : stack);
  }

  theme.push("", "  /* Type styles */");
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const emit = (name, size) => {
        line(theme, `text-${name}`, px(size));
        line(theme, `text-${name}--line-height`, String(s.lineHeight));
        if (s.letterSpacing) line(theme, `text-${name}--letter-spacing`, s.letterSpacing);
        line(theme, `text-${name}--font-weight`, String(s.fontWeight));
      };
      emit(s.name, s.fontSize);
      const phone = /(\d+(?:\.\d+)?)px under (\d+)px/.exec(s.usage ?? "");
      if (phone) emit(`${s.name}-phone`, `${phone[1]}px`);
    }
  }

  root.push("  /* Motion */");
  for (const t of tokens.duration.tokens) line(root, t.name, t.value);
  for (const t of tokens.easing.tokens) line(root, t.name, t.value);
  root.push("", "  /* Spacing (Tailwind's 4 px scale covers these: space-4 = p-4) */");
  for (const t of tokens.spacing.tokens) line(root, t.name, t.value);
  root.push("", "  /* Borders */");
  for (const t of tokens.border.tokens) line(root, t.name, t.value);

  return [
    "/* Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit by hand. */",
    "",
    "@theme {",
    ...theme,
    "}",
    "",
    ":root {",
    ...root,
    "}",
    "",
  ].join("\n");
}

export function readTokens(path = TOKENS_JSON) {
  return JSON.parse(readFileSync(path, "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = renderTokens(readTokens());
  writeFileSync(TOKENS_CSS, css);
  const colors = readTokens().color.tokens.length;
  console.log(`tokens: app/tokens.css (${colors} colors)`);
}
